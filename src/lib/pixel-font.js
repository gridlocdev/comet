export const CELL = 10;         // font pixels in a line: 1 above the capitals, 7 for them, 2 below
const glyphs = {};
for (const [ch, s] of Object.entries(G))
{
    const rows = s.split('/');
    glyphs[ch] = { w: rows[0].length, rows };
}
export const FONT = glyphs;
const blank = glyphs['?'];

const glyph = (ch)=> glyphs[ch] ?? blank;

// the width of a line in font pixels
export function measure(text)
{
    let w = 0;
    for (const ch of text) w += glyph(ch).w + 1;
    return Math.max(0, w - 1);
}

// every lit font pixel of a line as [x, y], x from its left edge and y from the top of its cell
export function pixels(text)
{
    const out = [];
    let pen = 0;
    for (const ch of text)
    {
        const g = glyph(ch);
        g.rows.forEach((row, y)=> { for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([pen + x, y + 1]); });
        pen += g.w + 1;
    }
    return out;
}
